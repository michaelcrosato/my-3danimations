// `npm run vectors [-- --check | --dense]`: the conformance vectors (WP-0.4), from the JavaScript originals at the
// pinned commits (`npm run pins -- fetch` first). With no flag it writes spec/vectors/ (README.md, manifest.json and
// the tier files); --check regenerates in memory and fails on any byte that differs, any file missing or stale, a
// frozen fixture whose SHA-256 moved, or a total over 10 MB; --dense also writes every clip decoded at 30 fps into
// .cache/vectors/tier2-dense/ (too large to commit). The frozen fixtures under frozen/ are never written here.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { finish, fmtMs, parseArgs, ROOT, usage, type Report, type Step } from "../run/cli.ts";
import { generate, SETS } from "./generate.ts";
import { stringify } from "../../spec/conformance/runner/json.ts";
import { loadCodec, loadSet, originDir } from "./oracle.ts";
import type { Pins } from "../doctrine/pins.ts";

const DIR = join(ROOT, "spec/vectors");
const MAX_BYTES = 10 * 1024 * 1024;
const sha256 = (s: string | Buffer) => createHash("sha256").update(s).digest("hex");

/** Every committed vector file under spec/vectors/, relative, except the frozen fixtures. */
function committed(): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    if (!existsSync(d)) return;
    for (const n of readdirSync(d)) {
      const p = join(d, n);
      if (statSync(p).isDirectory()) walk(p);
      else out.push(relative(DIR, p).split("\\").join("/"));
    }
  };
  walk(DIR);
  return out.filter((f) => !f.startsWith("frozen/")).sort();
}

/** The README and manifest that describe a generated file set. */
function describe(files: Map<string, string>, pins: Pins): Map<string, string> {
  const manifest = Object.fromEntries([...files].sort(([a], [b]) => (a < b ? -1 : 1)).map(([p, s]) => [p, { bytes: Buffer.byteLength(s), sha256: sha256(s) }]));
  const total = Object.values(manifest).reduce((a, m) => a + m.bytes, 0);
  const repos = Object.entries(pins.repos).map(([n, r]) => `- ${n} \`${r.sha}\` (${r.url})`).join("\n");
  const frozen = (pins.frozen ?? []).map((f) => `- \`${f.path.replace("spec/vectors/", "")}\`: ${f.from}; SHA-256 \`${f.sha256}\``).join("\n");
  const readme = `# Conformance vectors

Generated by \`npm run vectors\` (tools/vectors/) from the JavaScript originals at the pinned commits; never edited by
hand. \`npm run vectors -- --check\` regenerates them and compares byte for byte. The tiers and their tolerances are in
\`spec/conformance/tiers.md\`; \`manifest.json\` lists every file with its size and SHA-256 (${(total / 1024 / 1024).toFixed(2)} MB in all).

**Sources** (\`tools/pins.json\`):
${repos}

**Numbers** are the shortest decimal that parses back to the same double, \`-0\` kept. Body points are in the origin's
POINTS order (36 points, each forward, right, up), millimetres in tiers 1a and 3, whole micrometres in tier 2.

| Path | Tier | What it holds |
|---|---|---|
| \`tier1a/rig.json\` | 1a | The tiny rig's captured body points, the measured rest, and per clip reduce, fit and text (bit for bit) |
| \`tier1a/cmu-09_02.json\` | 1a | The same for two picks of CMU take 09_02 (a loop cut at its best cycle, and a burst) |
| \`tier1b/rig.gltf\` | 1b | The tiny rig as glTF JSON (buffer embedded); packed as .glb it is the reader's input (its SHA-256 is in tier1a/rig.json) |
| \`tier1b/rig-catalog.json\` | 1b | The catalog the importer read for the rig (tags, descriptions) |
| \`tier1b/cmu/\` | 1b | CMU subject 09's skeleton (\`09.asf\`), take 09_02 (\`09_02.amc\`) and the picks catalog |
| \`tier2/<SET>.json\` | 2 | Every curated clip decoded on its reference body at each key and at three in-betweens; mirror and text checks |
| \`tier3/bodies.json\` | 3 | Bodies of other proportions: seven generated rigs and the sets' own bodies |
| \`frozen/\` | frozen | Fixtures from my-3dge, checked by SHA-256 and never regenerated (below) |

**Frozen fixtures:**
${frozen}

**Licenses.** The vectors derived from the tiny rig are MIT, like the code. \`tier1b/cmu/\` and \`tier1a/cmu-09_02.json\`
are CMU motion capture data: "This data is free for use in research projects. You may include this data in
commercially-sold products, but you may not resell this data directly, even in converted form." (CMU Graphics Lab
Motion Capture Database, mocap.cs.cmu.edu; created with funding from NSF EIA-0196217.) Tier 2's clips keep their sets'
licenses: QUATERNIUS CC0 1.0, MESH2MOTION CC0 1.0 pending the audit in WP-5.3, CMU under the notice above.
`;
  return new Map([
    ["README.md", readme],
    ["manifest.json", stringify({ about: "Every generated vector file: bytes and SHA-256. Written by npm run vectors.", files: manifest }) + "\n"],
  ]);
}

/** The 30 fps decodes of every curated clip, written into .cache/vectors/tier2-dense/. */
function dense(): string[] {
  const MR = loadCodec(ROOT);
  const out = join(ROOT, ".cache/vectors/tier2-dense");
  mkdirSync(out, { recursive: true });
  const written: string[] = [];
  const buf = new Float32Array(MR.P * 3);
  for (const name of SETS) {
    const set = loadSet(ROOT, name);
    const ids = Object.keys(set.sources);
    const base = set.sources[ids[0]!]!.rest;
    const clips: Record<string, unknown> = {};
    for (const [n, clip] of Object.entries(set.clips)) {
      const src = set.sources[clip.src ?? ""] ? clip.src! : ids[0]!;
      const R = { ...base, spineW: set.sources[src]!.rest.spineW, neckW: set.sources[src]!.rest.neckW };
      const frames: number[][] = [];
      for (let f = 0; f <= Math.round(clip.dur * 30); f++) frames.push(Array.from(MR.pose(R, clip, f / 30, buf), (v) => Math.round(v * 1000)));
      clips[n] = { restSrc: src, frames };
    }
    const file = join(out, `${set.set}.json`);
    writeFileSync(file, stringify({ about: "Every clip decoded at 30 fps (t = f / 30 up to dur), whole micrometres", clips }) + "\n");
    written.push(relative(ROOT, file));
  }
  return written;
}

if (import.meta.main) {
  const specs = [
    { name: "check", help: "regenerate in memory and compare byte for byte" },
    { name: "dense", help: "also write the 30 fps decodes into .cache/vectors/tier2-dense/" },
  ];
  let parsed;
  try {
    parsed = parseArgs(process.argv.slice(2), specs);
    if (parsed.positionals.length) throw new Error(`unexpected argument "${parsed.positionals[0]}"`);
  } catch (err) {
    usage("vectors", err, specs);
  }
  const t0 = performance.now();
  const steps: Step[] = [];
  const pins = JSON.parse(readFileSync(join(ROOT, "tools/pins.json"), "utf8")) as Pins;
  const origin = originDir(ROOT);
  if (!existsSync(join(origin, "src/mocap/readable.js")) || !existsSync(join(ROOT, ".cache/src/shardfall/crates"))) {
    finish({ tool: "vectors", ok: false, verdict: "vectors: FAIL, the pinned sources are not in .cache/src/", steps: [], warnings: [], ms: 0, next: "npm run pins -- fetch, then rerun" }, parsed);
  }
  let files: Map<string, string>;
  try {
    files = await generate(ROOT, join(ROOT, ".cache/vectors-work"));
  } catch (err) {
    finish({ tool: "vectors", ok: false, verdict: `vectors: FAIL while generating: ${(err as Error).message}`, steps: [], warnings: [], ms: performance.now() - t0, next: "check the pins (npm run pins -- check) and the oracle" }, parsed);
  }
  for (const [p, s] of describe(files, pins)) files.set(p, s);
  const generated = [...files.values()].reduce((a, s) => a + Buffer.byteLength(s), 0);
  const frozenBytes = (pins.frozen ?? []).reduce((a, f) => a + (existsSync(join(ROOT, f.path)) ? statSync(join(ROOT, f.path)).size : 0), 0);
  const total = generated + frozenBytes;
  steps.push({ name: "generate", ok: true, ms: performance.now() - t0, summary: `${files.size} files, ${(generated / 1024 / 1024).toFixed(2)} MB` });
  steps.push({ name: "size", ok: total <= MAX_BYTES, ms: 0, summary: `${(total / 1024 / 1024).toFixed(2)} of 10 MB committed, frozen fixtures included`, detail: total > MAX_BYTES ? ["the committed vectors are over 10 MB: move the largest into .cache/ (as --dense does)"] : [] });
  const frozenProblems: string[] = [];
  for (const fz of pins.frozen ?? []) {
    const p = join(ROOT, fz.path);
    if (!existsSync(p)) frozenProblems.push(`${fz.path} is missing: copy it from ${fz.from}`);
    else if (sha256(readFileSync(p)) !== fz.sha256) frozenProblems.push(`${fz.path} does not match its SHA-256 in tools/pins.json: frozen fixtures are never edited`);
  }
  steps.push({ name: "frozen", ok: frozenProblems.length === 0, ms: 0, summary: `${(pins.frozen ?? []).length} fixtures`, detail: frozenProblems });
  if (parsed.flags.check) {
    const problems: string[] = [];
    for (const [p, s] of files) {
      const file = join(DIR, p);
      if (!existsSync(file)) problems.push(`${p} is missing: run npm run vectors`);
      else if (readFileSync(file, "utf8") !== s) problems.push(`${p} differs from what the oracle writes: the oracle, the pins or the generator changed`);
    }
    for (const p of committed()) if (!files.has(p)) problems.push(`${p} is stale: no generator writes it`);
    steps.push({ name: "compare", ok: problems.length === 0, ms: 0, summary: problems.length ? `${problems.length} file(s) differ` : `${files.size} files byte for byte`, detail: problems });
  } else {
    for (const p of committed()) if (!files.has(p)) rmSync(join(DIR, p));
    for (const [p, s] of files) {
      mkdirSync(dirname(join(DIR, p)), { recursive: true });
      writeFileSync(join(DIR, p), s);
    }
    steps.push({ name: "write", ok: true, ms: 0, summary: `spec/vectors/: ${files.size} files` });
  }
  if (parsed.flags.dense) {
    const d0 = performance.now();
    const written = dense();
    steps.push({ name: "dense", ok: true, ms: performance.now() - d0, summary: written.join(", ") });
  }
  const ms = performance.now() - t0;
  const ok = steps.every((s) => s.ok);
  const report: Report = { tool: "vectors", ok, verdict: `vectors: ${ok ? "PASS" : "FAIL"}${parsed.flags.check ? " (--check)" : ""} in ${fmtMs(ms)}`, steps, warnings: [], ms, next: ok ? (parsed.flags.check ? "npm test" : "commit spec/vectors/ with the change that moved them, saying why") : "fix the listed files; vectors change only in a commit that says why" };
  finish(report, parsed);
}
