const BOX = "##### #...# #...# #...# #...# #...# #####";
/** Characters drawn as another (an en dash as a hyphen, µ as U). */
const SAME: Readonly<Record<string, string>> = { "–": "-", "—": "-", "µ": "U", "−": "-" };

/** Glyph width and height in font pixels, and the advance from one character to the next. */
export const GLYPH = { width: 5, height: 7, advance: 6 } as const;

/** Each glyph's ink as 7 rows of 5 bits (bit 4 the leftmost column). */
const GLYPHS = new Map<string, number[]>(Object.entries(ROWS).map(([ch, rows]) => [ch, bits(rows)]));
function bits(rows: string): number[] {
  return rows.split(" ").map((r) => [...r].reduce((v, c) => v * 2 + (c === "#" ? 1 : 0), 0));
}
const glyph = (ch: string): number[] => GLYPHS.get(SAME[ch] ?? ch.toUpperCase()) ?? bits(BOX);

/** The width in pixels of `str` drawn at `scale`. */
export function textWidth(str: string, scale = 1): number {
  const n = [...str].length;
  return n ? (n * GLYPH.advance - 1) * scale : 0;
}

/** Draws `str` with its top-left at (x, y), each font pixel `scale` pixels square; `bg` paints a box behind it first. */
export function text(img: Image, x: number, y: number, str: string, color: Rgb = [40, 40, 40], scale = 1, bg?: Rgb): void {
  if (bg) rect(img, x - scale, y - scale, textWidth(str, scale) + 2 * scale, (GLYPH.height + 2) * scale, bg);
  let cx = Math.round(x);
  for (const ch of str) {
    const g = glyph(ch);
    for (let r = 0; r < GLYPH.height; r++) {
      for (let c = 0; c < GLYPH.width; c++) {
        if (!((g[r]! >> (GLYPH.width - 1 - c)) & 1)) continue;
        if (scale === 1) pixel(img, cx + c, Math.round(y) + r, color);
        else rect(img, cx + c * scale, Math.round(y) + r * scale, scale, scale, color);
      }
    }
    cx += GLYPH.advance * scale;
  }
}
